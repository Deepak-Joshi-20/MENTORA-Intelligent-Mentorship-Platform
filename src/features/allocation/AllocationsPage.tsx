import React, { useState } from 'react';
import { useApp } from '../../context/AppContext';
import { AllocationResult } from '../../types';
import {
  Search,
  Download,
  Printer,
  CheckCircle2,
  AlertCircle,
  Eye,
  Zap,
  Sparkles,
  X,
  Clock,
  ArrowRight,
} from 'lucide-react';
import { DashboardHeaderIllustration } from '../../components/common/BookIllustration';

export const AllocationsPage: React.FC = () => {
  const { allocations, students, lastBatchRun, setActiveNav } = useApp();

  const [search, setSearch] = useState('');
  const [selectedAllocation, setSelectedAllocation] = useState<AllocationResult | null>(null);

  const filteredAllocations = allocations.filter(a =>
    a.student_name.toLowerCase().includes(search.toLowerCase()) ||
    a.mentor_name.toLowerCase().includes(search.toLowerCase()) ||
    a.allocation_id.toLowerCase().includes(search.toLowerCase())
  );

  const unallocatedList = students.filter(s => s.allocation_status !== 'Allocated');

  const exportCSV = () => {
    const headers = [
      'Allocation_ID',
      'Student_ID',
      'Student_Name',
      'Mentor_ID',
      'Mentor_Name',
      'Mentor_Type',
      'Match_Score',
      'Subject_Score_40',
      'Interest_Score_25',
      'Availability_Score_20',
      'Workload_Score_15',
      'Allocation_Date',
    ];

    const rows = allocations.map(a => [
      a.allocation_id,
      a.student_id,
      `"${a.student_name}"`,
      a.mentor_id,
      `"${a.mentor_name}"`,
      a.mentor_type,
      a.match_score,
      a.score_breakdown.subject_score,
      a.score_breakdown.interest_score,
      a.score_breakdown.availability_score,
      a.score_breakdown.workload_score,
      a.allocation_date,
    ]);

    const csvContent =
      'data:text/csv;charset=utf-8,' +
      [headers.join(','), ...rows.map(e => e.join(','))].join('\n');

    const encodedUri = encodeURI(csvContent);
    const link = document.createElement('a');
    link.setAttribute('href', encodedUri);
    link.setAttribute('download', `mentora_allocations_${Date.now()}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      {/* Visually engaging page header with soft background treatment & illustration */}
      <div className="rounded-2xl bg-gradient-to-r from-white via-[#FFF9F0] to-[#E5EDFC]/30 border border-[#EAE2D8] p-6 lg:p-7 shadow-xs relative overflow-hidden">
        <div className="absolute right-0 top-0 bottom-0 w-72 pointer-events-none opacity-60 hidden md:block">
          <DashboardHeaderIllustration className="w-full h-full" />
        </div>

        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 relative z-10">
          <div className="space-y-1.5 max-w-xl">
            <div className="inline-flex items-center gap-2 px-2.5 py-0.5 rounded-full bg-[#E5EDFC] text-[#5478D4] font-semibold text-[11px]">
              <span className="w-1.5 h-1.5 rounded-full bg-[#5478D4]" />
              <span>ROSTER REGISTRY · AUDIT TRAIL</span>
            </div>
            <h2 className="font-heading text-2xl sm:text-3xl font-extrabold text-[#202C45] tracking-tight">
              Allocation Roster
            </h2>
            <p className="text-xs sm:text-sm text-[#64748B] leading-relaxed">
              Committed pairings generated by the greedy matching engine. Every match features an itemized breakdown of subject overlap, shared interests, availability, and advisor load balance.
            </p>
          </div>

          <div className="flex flex-wrap items-center gap-2.5 shrink-0">
            <button
              onClick={() => setActiveNav('smart-allocation')}
              className="px-4 py-2.5 rounded-xl bg-[#F07857] hover:bg-[#DE6240] text-white text-xs font-bold transition flex items-center gap-2 shadow-xs active:scale-95"
            >
              <Zap className="w-4 h-4 fill-white" />
              <span>Matching Engine</span>
            </button>
            <button
              onClick={exportCSV}
              disabled={allocations.length === 0}
              className="px-3.5 py-2.5 rounded-xl border border-[#EAE2D8] bg-white hover:bg-[#FFF9F0] text-[#202C45] text-xs font-bold transition flex items-center gap-1.5 disabled:opacity-40 shadow-2xs"
            >
              <Download className="w-3.5 h-3.5 text-[#5478D4]" />
              <span>Export CSV</span>
            </button>
            <button
              onClick={handlePrint}
              className="px-3.5 py-2.5 rounded-xl border border-[#EAE2D8] bg-white hover:bg-[#FFF9F0] text-[#202C45] text-xs font-bold transition flex items-center gap-1.5 shadow-2xs"
            >
              <Printer className="w-3.5 h-3.5 text-[#64748B]" />
              <span>Print Sheet</span>
            </button>
          </div>
        </div>
      </div>

      {/* Summary Stats Cards with Distinct Coordinated Visual Identities */}
      <div className="grid grid-cols-1 sm:grid-cols-4 gap-3.5 text-xs">
        {/* Allocated Pairs (VISUALLY DISTINCT WITH TEAL) */}
        <div className="p-4 rounded-xl bg-white border-2 border-[#63AFA3] shadow-xs relative overflow-hidden">
          <div className="flex items-center justify-between text-[#64748B] mb-1">
            <span className="text-[10px] font-mono uppercase font-bold text-[#63AFA3] tracking-wider">
              ALLOCATED PAIRS
            </span>
            <div className="w-6 h-6 rounded-md bg-[#63AFA3] text-white flex items-center justify-center">
              <CheckCircle2 className="w-3.5 h-3.5 stroke-[2.5]" />
            </div>
          </div>
          <span className="text-2xl font-heading font-black text-[#63AFA3] tabular-nums mt-0.5 block">
            {allocations.length}
          </span>
          <span className="text-[10px] text-[#64748B] mt-1 block">Active guidance pairs</span>
        </div>

        {/* Awaiting Allocation (CORAL) */}
        <div className="p-4 rounded-xl bg-white border border-[#F07857]/40 shadow-xs hover:border-[#F07857] transition-all">
          <div className="flex items-center justify-between text-[#64748B] mb-1">
            <span className="text-[10px] font-mono uppercase font-bold text-[#F07857] tracking-wider">
              AWAITING ALLOCATION
            </span>
            <div className="w-6 h-6 rounded-md bg-[#FFF4E6] text-[#F07857] flex items-center justify-center">
              <AlertCircle className="w-3.5 h-3.5" />
            </div>
          </div>
          <span className="text-2xl font-heading font-black text-[#F07857] tabular-nums mt-0.5 block">
            {unallocatedList.length}
          </span>
          <span className="text-[10px] text-[#64748B] mt-1 block">Mentees in queue</span>
        </div>

        {/* Average Score (COBALT) */}
        <div className="p-4 rounded-xl bg-white border border-[#5478D4]/40 shadow-xs hover:border-[#5478D4] transition-all">
          <div className="flex items-center justify-between text-[#64748B] mb-1">
            <span className="text-[10px] font-mono uppercase font-bold text-[#5478D4] tracking-wider">
              AVERAGE SCORE
            </span>
            <div className="w-6 h-6 rounded-md bg-[#E5EDFC] text-[#5478D4] flex items-center justify-center">
              <Sparkles className="w-3.5 h-3.5 fill-[#5478D4]" />
            </div>
          </div>
          <span className="text-2xl font-heading font-black text-[#5478D4] tabular-nums mt-0.5 block">
            {allocations.length > 0
              ? (allocations.reduce((acc, a) => acc + a.match_score, 0) / allocations.length).toFixed(1)
              : '0.0'}
            <span className="text-xs font-semibold text-[#64748B] ml-1">/100</span>
          </span>
          <span className="text-[10px] text-[#64748B] mt-1 block">Mean compatibility</span>
        </div>

        {/* Last Engine Batch */}
        <div className="p-4 rounded-xl bg-white border border-[#EAE2D8] shadow-xs">
          <div className="flex items-center justify-between text-[#64748B] mb-1">
            <span className="text-[10px] font-mono uppercase font-bold tracking-wider">
              LAST ENGINE BATCH
            </span>
            <div className="w-6 h-6 rounded-md bg-[#FFF9F0] text-[#64748B] flex items-center justify-center">
              <Clock className="w-3.5 h-3.5" />
            </div>
          </div>
          <span className="text-sm font-heading font-bold text-[#202C45] mt-1 block">
            {lastBatchRun ? new Date(lastBatchRun.run_timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' }) : 'Pending run'}
          </span>
          <span className="text-[10px] text-[#64748B] mt-1 block">
            {lastBatchRun ? `${lastBatchRun.successful_allocations.length} matched in batch` : 'Greedy algorithm ready'}
          </span>
        </div>
      </div>

      {/* Search and Polished Table */}
      <div className="bg-white rounded-2xl border border-[#EAE2D8] shadow-xs overflow-hidden">
        <div className="p-4 border-b border-[#EAE2D8] flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-[#FFF9F0]/40">
          <div className="relative flex-1 max-w-md">
            <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-[#64748B]" />
            <input
              type="text"
              value={search}
              onChange={e => setSearch(e.target.value)}
              placeholder="Search by student name, advisor, or ID..."
              className="w-full pl-9 pr-3.5 py-2 text-xs bg-white border border-[#EAE2D8] rounded-xl text-[#202C45] focus:outline-none focus:border-[#5478D4] focus:ring-1 focus:ring-[#5478D4] transition"
            />
          </div>
          <span className="text-xs font-semibold text-[#64748B] tabular-nums">
            Showing {filteredAllocations.length} pairing(s)
          </span>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="bg-[#FFF9F0] border-b border-[#EAE2D8] text-[10px] font-mono uppercase tracking-wider text-[#64748B]">
              <tr>
                <th className="px-4 py-3.5 font-bold">Ref ID</th>
                <th className="px-4 py-3.5 font-bold">Student Mentee</th>
                <th className="px-4 py-3.5 font-bold">Assigned Advisor</th>
                <th className="px-3 py-3.5 font-bold">Role</th>
                <th className="px-3 py-3.5 font-bold text-center">Score</th>
                <th className="px-3 py-3.5 font-bold text-center">Subj (40)</th>
                <th className="px-3 py-3.5 font-bold text-center">Int (25)</th>
                <th className="px-3 py-3.5 font-bold text-center">Avail (20)</th>
                <th className="px-3 py-3.5 font-bold text-center">Work (15)</th>
                <th className="px-4 py-3.5 text-right font-bold">Audit</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-[#EAE2D8]">
              {filteredAllocations.length === 0 ? (
                <tr>
                  <td colSpan={10} className="px-6 py-14 text-center text-xs text-[#64748B]">
                    <div className="max-w-xs mx-auto space-y-2">
                      <Zap className="w-7 h-7 text-[#F07857] mx-auto opacity-60" />
                      <div className="font-heading font-bold text-[#202C45]">No allocations on record</div>
                      <p className="text-[11px] text-[#64748B]">Execute the greedy matching engine to pair students with advisors.</p>
                      <button
                        onClick={() => setActiveNav('smart-allocation')}
                        className="px-3 py-1.5 rounded-lg bg-[#F07857] text-white font-bold text-[11px] inline-flex items-center gap-1.5"
                      >
                        Run Engine Now
                      </button>
                    </div>
                  </td>
                </tr>
              ) : (
                filteredAllocations.map((alc, idx) => (
                  <tr
                    key={alc.allocation_id}
                    className={`transition-colors ${idx % 2 === 1 ? 'bg-[#FFF9F0]/30' : 'bg-white'} hover:bg-[#FFF4E6]/50`}
                  >
                    <td className="px-4 py-3.5 font-mono font-bold text-[#F07857]">
                      {alc.allocation_id}
                    </td>

                    <td className="px-4 py-3.5">
                      <div className="font-heading font-bold text-[#202C45]">{alc.student_name}</div>
                      <div className="text-[10px] text-[#64748B] font-mono">{alc.student_id}</div>
                    </td>

                    <td className="px-4 py-3.5">
                      <div className="font-heading font-bold text-[#5478D4]">{alc.mentor_name}</div>
                      <div className="text-[10px] text-[#64748B] font-mono">{alc.mentor_id}</div>
                    </td>

                    <td className="px-3 py-3.5">
                      <span className={`text-[10px] font-semibold px-2 py-0.5 rounded-md ${
                        alc.mentor_type === 'Faculty'
                          ? 'bg-[#E5EDFC] text-[#5478D4]'
                          : 'bg-[#F9E3D9] text-[#F07857]'
                      }`}>
                        {alc.mentor_type}
                      </span>
                    </td>

                    {/* Prominent Score Column */}
                    <td className="px-3 py-3.5 text-center">
                      <span className="inline-flex items-center justify-center px-2.5 py-1 rounded-lg bg-[#E5EDFC] text-[#5478D4] font-heading font-black text-xs tabular-nums border border-[#5478D4]/20 shadow-2xs">
                        {alc.match_score} pts
                      </span>
                    </td>

                    <td className="px-3 py-3.5 text-center font-heading font-semibold text-[#202C45] tabular-nums">
                      {alc.score_breakdown.subject_score}
                    </td>

                    <td className="px-3 py-3.5 text-center font-heading font-semibold text-[#64748B] tabular-nums">
                      {alc.score_breakdown.interest_score}
                    </td>

                    <td className="px-3 py-3.5 text-center font-heading font-semibold text-[#64748B] tabular-nums">
                      {alc.score_breakdown.availability_score}
                    </td>

                    <td className="px-3 py-3.5 text-center font-heading font-semibold text-[#64748B] tabular-nums">
                      {alc.score_breakdown.workload_score}
                    </td>

                    <td className="px-4 py-3.5 text-right">
                      <button
                        onClick={() => setSelectedAllocation(alc)}
                        className="px-2.5 py-1 rounded-lg border border-[#EAE2D8] bg-white hover:bg-[#E5EDFC] text-[#5478D4] hover:border-[#5478D4] text-xs font-semibold transition inline-flex items-center gap-1 shadow-2xs"
                        title="View Score Verification"
                      >
                        <Eye className="w-3.5 h-3.5" />
                        <span>Audit</span>
                      </button>
                    </td>
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Detail Breakdown Modal */}
      {selectedAllocation && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-[#202C45]/40 backdrop-blur-xs">
          <div className="bg-white rounded-3xl shadow-2xl max-w-lg w-full p-6 border border-[#EAE2D8] space-y-4 text-[#202C45]">
            <div className="flex items-center justify-between pb-3 border-b border-[#EAE2D8]">
              <div>
                <h3 className="font-heading text-base font-extrabold text-[#202C45]">
                  Match Score Audit: {selectedAllocation.allocation_id}
                </h3>
                <p className="text-xs text-[#64748B] mt-0.5">
                  {selectedAllocation.student_name} &harr; {selectedAllocation.mentor_name}
                </p>
              </div>
              <button
                onClick={() => setSelectedAllocation(null)}
                className="p-1 rounded-lg text-[#64748B] hover:text-[#202C45] hover:bg-[#FFF9F0]"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <div className="p-4 rounded-2xl bg-[#FFF9F0] border border-[#EAE2D8] flex items-center justify-between">
              <div>
                <span className="font-heading font-bold text-[#202C45] block">Total Compatibility Score</span>
                <span className="text-[11px] text-[#64748B]">Algorithmically verified allocation</span>
              </div>
              <span className="font-heading text-2xl font-black text-[#5478D4] tabular-nums">
                {selectedAllocation.match_score} / 100
              </span>
            </div>

            <div className="space-y-2.5 text-xs">
              <div className="p-3 rounded-xl bg-white border border-[#EAE2D8] flex items-center justify-between">
                <div>
                  <span className="font-heading font-bold text-[#202C45] block">Subject Match (Weight: 40)</span>
                  <span className="text-[11px] text-[#64748B]">Coverage of student challenge subjects</span>
                </div>
                <span className="font-heading font-bold text-[#F07857] tabular-nums">
                  {selectedAllocation.score_breakdown.subject_score} pts
                </span>
              </div>

              <div className="p-3 rounded-xl bg-white border border-[#EAE2D8] flex items-center justify-between">
                <div>
                  <span className="font-heading font-bold text-[#202C45] block">Interest Overlap (Weight: 25)</span>
                  <span className="text-[11px] text-[#64748B]">Shared technical affinity &amp; domain interests</span>
                </div>
                <span className="font-heading font-bold text-[#DE6240] tabular-nums">
                  {selectedAllocation.score_breakdown.interest_score} pts
                </span>
              </div>

              <div className="p-3 rounded-xl bg-white border border-[#EAE2D8] flex items-center justify-between">
                <div>
                  <span className="font-heading font-bold text-[#202C45] block">Availability (Weight: 20)</span>
                  <span className="text-[11px] text-[#64748B]">Common weekly meeting slots</span>
                </div>
                <span className="font-heading font-bold text-[#5478D4] tabular-nums">
                  {selectedAllocation.score_breakdown.availability_score} pts
                </span>
              </div>

              <div className="p-3 rounded-xl bg-white border border-[#EAE2D8] flex items-center justify-between">
                <div>
                  <span className="font-heading font-bold text-[#202C45] block">Workload Balance (Weight: 15)</span>
                  <span className="text-[11px] text-[#64748B]">Dynamic capacity weighting</span>
                </div>
                <span className="font-heading font-bold text-[#63AFA3] tabular-nums">
                  {selectedAllocation.score_breakdown.workload_score} pts
                </span>
              </div>
            </div>

            <div className="pt-3 border-t border-[#EAE2D8] flex justify-end">
              <button
                onClick={() => setSelectedAllocation(null)}
                className="px-5 py-2 rounded-xl bg-[#F07857] text-white font-bold text-xs shadow-xs hover:bg-[#DE6240] active:scale-95"
              >
                Close Audit
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
